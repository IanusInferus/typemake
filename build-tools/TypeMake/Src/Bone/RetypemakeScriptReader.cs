using System;
using System.Collections.Generic;
using System.Linq;
using System.IO;
using System.Text.RegularExpressions;

namespace TypeMake
{
    public static class RetypemakeScriptReader
    {
        public static void Read(PathString RetypemakeScriptPath)
        {
            String[] Lines;
            Regex rQuotedVariable = null;
            Regex rVariable;
            var ReplacePercent = false;
            if (RetypemakeScriptPath.Extension.ToLowerInvariant() == "cmd")
            {
                Lines = File.ReadAllLines(RetypemakeScriptPath, System.Text.Encoding.Default);
                // SET is a CMD built-in. Quoted assignments use only their first and last
                // quotes as wrappers; the unquoted form generated by TypeMake uses caret
                // escapes for CMD metacharacters.
                // https://learn.microsoft.com/en-us/windows-server/administration/windows-commands/set_1
                // https://learn.microsoft.com/en-us/windows-server/administration/windows-commands/cmd
                rQuotedVariable = new Regex(@"^set\s+""(?<Key>[^=]+)=(?<Value>.*)""\s*$", RegexOptions.IgnoreCase);
                rVariable = new Regex(@"^set\s+(?<Key>[^=\s""]+)=(?<Value>.*)$", RegexOptions.IgnoreCase);
                ReplacePercent = true;
            }
            else if (RetypemakeScriptPath.Extension.ToLowerInvariant() == "sh")
            {
                Lines = File.ReadAllLines(RetypemakeScriptPath, new System.Text.UTF8Encoding(false));
                rVariable = new Regex(@"^export\s+(?<Key>[^=]+)=('(?<Value>.*)'|(?<Value>.*))\s*$");
            }
            else
            {
                throw new InvalidOperationException("InvalidRetypemakeScript");
            }
            foreach (var Line in Lines)
            {
                var QuotedMatch = rQuotedVariable?.Match(Line);
                var Match = QuotedMatch != null && QuotedMatch.Success ? QuotedMatch : rVariable.Match(Line);
                if (Match.Success)
                {
                    var Key = Match.Result("${Key}");
                    var Value = Match.Result("${Value}");
                    if (ReplacePercent)
                    {
                        if (QuotedMatch != null && QuotedMatch.Success)
                        {
                            Key = Key.Replace("%%", "%");
                            Value = Value.Replace("%%", "%");
                        }
                        else
                        {
                            Key = Shell.ParseArgumentsForCmdSet(Key);
                            Value = Shell.ParseArgumentsForCmdSet(Value);
                        }
                    }
                    if ((Key == "BuildDirectory") && (Value.Contains("%") || Value.Contains("$")))
                    {
                        Environment.SetEnvironmentVariable(Key, RetypemakeScriptPath.FullPath.Parent);
                    }
                    else
                    {
                        Environment.SetEnvironmentVariable(Key, Value);
                    }
                }
            }
        }
    }
}
